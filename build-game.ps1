$ErrorActionPreference = 'Stop'
$moduleFiles = @('config.js', 'assets.js', 'ranking.js', 'input.js', 'game.js', 'main.js')
$assetSource = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'js/assets.js'))
$embedded = [ordered]@{}
foreach ($match in [regex]::Matches($assetSource, "'((?:asset|assets)/[^']+\.(?:png|svg|webp))'")) {
    $relative = $match.Groups[1].Value
    if ($embedded.Contains($relative)) { continue }
    $file = Join-Path $PSScriptRoot $relative
    if (!(Test-Path -LiteralPath $file)) { continue }
    $mime = if ($relative.EndsWith('.svg')) { 'image/svg+xml' } elseif ($relative.EndsWith('.webp')) { 'image/webp' } else { 'image/png' }
    $embedded[$relative] = "data:$mime;base64," + [Convert]::ToBase64String([IO.File]::ReadAllBytes($file))
}
$output = [Text.StringBuilder]::new()
[void]$output.AppendLine('// Generated by build-game.ps1. Edit js source files, then rebuild.')
[void]$output.AppendLine('(async () => { "use strict";')
[void]$output.AppendLine('const EMBEDDED_ASSETS = ' + ($embedded | ConvertTo-Json -Compress) + ';')
foreach ($moduleFile in $moduleFiles) {
    $source = [IO.File]::ReadAllText((Join-Path $PSScriptRoot "js/$moduleFile"))
    $source = [regex]::Replace($source, '(?m)^import\s+[^\r\n]+;\s*$', '')
    $source = [regex]::Replace($source, '\bexport\s+(?=(?:const|class|function|async)\b)', '')
    $source = $source.Replace('new URL(`../${path}`, import.meta.url).href', 'EMBEDDED_ASSETS[path]')
    if ($source.Contains('import.meta') -or $source -match '(?m)^import\s') { throw "Unsupported module syntax in $moduleFile" }
    [void]$output.AppendLine("// Source: $moduleFile")
    [void]$output.AppendLine($source)
}
[void]$output.AppendLine('})().catch(error => { console.error(error); const notice = document.getElementById("launch-help"); notice.hidden = false; notice.textContent = "Falha ao carregar o jogo: " + error.message; });')
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'js/game.bundle.js'), $output.ToString(), [Text.UTF8Encoding]::new($false))
Write-Host 'Versao local atualizada: abra index.html diretamente, sem servidor.'
